"""Fit smooth minimum-norm residuals over the unchanged r15 3D prior.

Raster silhouette normals and visible hairline samples transfer boundary motion
to a shared 12x16 chart. Horizontal pitch keys and the hanging lower locks stay
exact. Each pitch pose solves independently under the same regularizer/budget.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
S=np.linspace(-2,2,12)
Y=np.linspace(0,584,16)


def fade(y):
    t=np.clip((y-400)/35,0,1)
    return 1-t*t*(3-2*t)


def stencil(s,y):
    x=np.clip((s+2)/4*11,0,11);v=np.clip(y/584*15,0,15)
    i,j=min(10,int(x)),min(14,int(v));result=np.zeros(192)
    for xx,wx in [(i,1-(x-i)),(i+1,x-i)]:
        for yy,wy in [(j,1-(v-j)),(j+1,v-j)]:
            result[yy*12+xx]+=wx*wy*fade(y)
    return result


def regularizer():
    rows=[]
    for j in range(16):
        for i in range(12):
            for step,bound,index,weight in [(1,i,12,2),(12,j,16,50)]:
                if 0<bound<index-1:
                    r=np.zeros(192);k=j*12+i
                    r[k-step],r[k],r[k+step]=1,-2,1
                    rows.append(r*np.sqrt(weight))
    lap=np.array(rows)
    return lap.T@lap+.5*np.eye(192)


def empty_data():
    return dict(s=S.tolist(),y=Y.tolist(),regularization=dict(ridge=.5,xSecondDifference=2,ySecondDifference=50),poses=[
        dict(name=direction+suffix,yaw=yaw,pitch=pitch,du=np.zeros((192,2)).tolist())
        for direction,pitch in [('up',30),('down',-30)]
        for suffix,yaw in [('-left',-45),('',0),('-right',45)]])


def write(data):
    text=json.dumps(data,ensure_ascii=False,separators=(',',':'))
    (ROOT/'source/viewer/hair-solve.json').write_text(text+'\n')
    (ROOT/'bundle/hair-solve-data.mjs').write_text('// Generated by pipeline/fit_hair_solve.py.\nexport const HAIR_SOLVE='+text+';\n')


def observations(pose,feature,captures):
    from probe_hair_only import reference,read_mask,fill_holes,span
    ref=reference(feature);name=pose['name']
    crown=read_mask(captures/(name+'-crown.png'));face=read_mask(captures/(name+'-face.png'))
    head=fill_holes(crown|face);vertices=pose['vertices']
    xy=np.array([v['xy'] for v in vertices]);grid=np.array([stencil(v['s'],v['y']) for v in vertices])
    rows=[]

    def add(pixel,delta,weight,front=False,normal=(1.,0.)):
        distances=((xy-pixel)**2).sum(axis=1)
        if front:distances+=np.array([0 if v['front'] else 1e12 for v in vertices])
        ids=np.argpartition(distances,3)[:3]
        if distances[ids].min()>30**2:return
        w=1/np.maximum(.5,np.sqrt(distances[ids]));w/=w.sum()
        n=np.array(normal,float);n/=np.linalg.norm(n)
        rows.append((w@grid[ids],delta,weight,n))

    for y in range(80,401,20):
        current,target=span(head,y),span(ref['head'],y)
        if current and target:
            for side in [0,1]:
                lo,hi=span(ref['head'],y-4),span(ref['head'],y+4)
                slope=(hi[side]-lo[side])/8 if lo and hi else 0
                add([current[side],y],[target[side]-current[side],0],1,normal=(1,-slope))
    yy,xx=np.where(head);top=int(yy.min());top_x=float(np.median(xx[yy==top]))
    add([top_x,top],[0,int(np.where(ref['head'])[0].min())-top],8,normal=(0,1))
    a,b=span(ref['face'],330),span(face,330)
    if a and b:
        for x in range(max(a[0],b[0])+6,min(a[1],b[1])-6,8):
            old,new=np.flatnonzero(face[:700,x]),np.flatnonzero(ref['face'][:700,x])
            if len(old) and len(new):add([x,int(old[0])],[0,int(new[0])-int(old[0])],4,True,normal=(0,1))
    c,d,w,n=map(np.array,zip(*rows))
    return dict(name=name,yaw=pose['yaw'],pitch=pose['pitch'],c=c,d=d,w=w,normal=n)


def solve_residual(p,r):
    n=p['normal'];cx=p['c'].copy();cy=cx.copy()
    if p['yaw']==0:
        mirror=cx.reshape(-1,16,12)[:,:,::-1].reshape(-1,192)
        cx=(cx-mirror)*.5;cy=(cy+mirror)*.5
    c=np.concatenate([cx*n[:,0,None],cy*n[:,1,None]],axis=1)
    w=p['w'];d=np.sum(p['d']*n,axis=1)
    q=np.linalg.solve(c.T@(w[:,None]*c)+np.kron(np.eye(2),r),c.T@(w*d))
    du=q.reshape(2,192).T.copy()
    if p['yaw']==0:
        grid=du.reshape(16,12,2)
        grid[:,:,0]=(grid[:,:,0]-grid[:,::-1,0])*.5
        grid[:,:,1]=(grid[:,:,1]+grid[:,::-1,1])*.5
    error=d-c@q
    stats=dict(observations=len(d),duRms=float(np.sqrt(np.mean(np.sum(du**2,axis=1)))),
               duMax=float(np.linalg.norm(du,axis=1).max()),
               predictedRms=float(np.sqrt(np.average(error**2,weights=w))),
               priorRms=float(np.sqrt(np.average(d**2,weights=w))))
    return dict(name=p['name'],yaw=p['yaw'],pitch=p['pitch'],du=du.tolist(),stats=stats)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--captures',default='debug/hair_solve_prior')
    parser.add_argument('--initialize',action='store_true')
    args=parser.parse_args();data=empty_data()
    if args.initialize:write(data);return
    source=json.loads(subprocess.check_output(['node',str(ROOT/'pipeline/hair_solve_inputs.mjs')],timeout=60))
    features={p['name']:p for p in json.loads((ROOT/'source/viewer/face-feature-fit.json').read_text())['poses']}
    paths=['bundle/hair-shell.mjs','bundle/hair-surface.mjs','bundle/dome-data.mjs','source/viewer/face-feature-fit.json']
    hashes={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in paths}
    if json.loads((ROOT/args.captures/'sources.json').read_text())!=hashes:
        raise ValueError('Prior capture is stale; run capture_hair_solve_prior.py')
    systems=[observations(p,features[p['name']],ROOT/args.captures) for p in source];poses=[];r=regularizer()
    for system in systems:
        for iteration in range(20):
            pose=solve_residual(system,r*2**iteration)
            if pose['stats']['duRms']<=6 and pose['stats']['duMax']<=22:break
        else:raise ValueError('Residual budget infeasible')
        pose['regularization']=dict(ridge=.5*2**iteration,xSecondDifference=2*2**iteration,ySecondDifference=50*2**iteration)
        poses.append(pose)
    data.update(poses=poses,captureDirectory=args.captures,method='unchanged r15 3D prior; independent smooth 12x16 Tikhonov residual charts',
                sources=hashes)
    write(data);print(json.dumps([dict(name=p['name'],**p['stats']) for p in poses],ensure_ascii=False))


if __name__=='__main__':main()
