ROOT=Path(__file__).resolve().parents[1]
S=np.linspace(-2,2,12)
Y=np.linspace(0,545,16)


def fade(y):
    t=np.clip((y-515)/30,0,1)
    return 1-t*t*(3-2*t)


def stencil(s,y):
    x=np.clip((s+2)/4*11,0,11);v=np.clip(y/545*15,0,15)
    i,j=min(10,int(x)),min(14,int(v));result=np.zeros(192)
    for xx,wx in [(i,1-(x-i)),(i+1,x-i)]:
        for yy,wy in [(j,1-(v-j)),(j+1,v-j)]:
            result[yy*12+xx]+=wx*wy*fade(y)
    return result


def regularizer():
    rows=[]
    for j in range(16):
        for i in range(12):
            for step,bound,index,weight in [(1,i,12,2),(12,j,16,50)]:
                if 0<bound<index-1:
                    r=np.zeros(192);k=j*12+i
                    r[k-step],r[k],r[k+step]=1,-2,1
                    rows.append(r*np.sqrt(weight))
    lap=np.array(rows)
    return lap.T@lap+.5*np.eye(192)


def empty_data():
    return dict(s=S.tolist(),y=Y.tolist(),regularization=dict(ridge=.5,xSecondDifference=2,ySecondDifference=50),poses=[
        dict(name=direction+suffix,yaw=yaw,pitch=pitch,du=np.zeros((192,2)).tolist())
        for direction,pitch in [('up',30),('down',-30)]
        for suffix,yaw in [('-left',-45),('',0),('-right',45)]])


