def observations(pose,feature,captures,current_du=None,basis=None):
    from probe_hair_only import reference,read_mask,fill_holes,span
    ref=reference(feature);name=pose['name']
    crown=read_mask(captures/(name+'-crown.png'));face=read_mask(captures/(name+'-face.png'))
    head=fill_holes(crown|face);vertices=pose['vertices']
    grid=np.array([(basis or stencil)(v['s'],v['y']) for v in vertices])
    du=np.zeros((192,2)) if current_du is None else np.array(current_du)
    xy=np.array([v['xy'] for v in vertices])+grid@du
    from hair_solve_quality import raster_stencil_sampler
    sample=raster_stencil_sampler(pose,xy,grid,ROOT/'bundle/assets/texture_00.png') if pose.get('triangles') else None
    rows=[]

    def add(pixel,delta,weight,front=False,normal=(1.,0.)):
        if sample is not None:
            c=sample(pixel,front)
            if c is None:return
        else:
            distances=((xy-pixel)**2).sum(axis=1)
            if front:distances+=np.array([0 if v['front'] else 1e12 for v in vertices])
            ids=np.argpartition(distances,3)[:3]
            if distances[ids].min()>30**2:return
            w=1/np.maximum(.5,np.sqrt(distances[ids]));w/=w.sum();c=w@grid[ids]
        n=np.array(normal,float);n/=np.linalg.norm(n)
        rows.append((c,np.array(delta)+c@du,weight,n))

    for y in range(60,521,16):
        current,target=span(head,y),span(ref['head'],y)
        if current and target:
            for side in [0,1]:
                lo,hi=span(ref['head'],y-4),span(ref['head'],y+4)
                slope=(hi[side]-lo[side])/8 if lo and hi else 0
                add([current[side],y],[target[side]-current[side],0],silhouette_weight(y,slope),normal=(1,-slope))
    yy,xx=np.where(head);top=int(yy.min());top_x=xx[yy==top]
    top_x=top_x[::max(1,len(top_x)//8)]
    for x in top_x:add([int(x),top+1],[0,int(np.where(ref['head'])[0].min())-top],500/len(top_x),normal=(0,1))
    prior_face=read_mask(ROOT/'debug/hair_solve_prior'/(name+'-face.png'))
    columns=np.flatnonzero(ref['face'][:550].any(axis=0)&prior_face[:550].any(axis=0))
    if len(columns):
        for x in range(int(columns[0])+6,int(columns[-1])-6,8):
            old,new=np.flatnonzero(face[:700,x]),np.flatnonzero(ref['face'][:700,x])
            if len(old) and len(new) and 150<=new[0]<=450:
                lo,hi=np.flatnonzero(ref['face'][:700,x-4]),np.flatnonzero(ref['face'][:700,x+4])
                slope=(int(hi[0])-int(lo[0]))/8 if len(lo) and len(hi) else 0
                add([x,int(old[0])-1],[0,int(new[0])-int(old[0])],20*(1+slope**2),True,normal=(-slope,1))
    if pose['yaw'] and pose['pitch']<0:
        right=pose['yaw']<0
        for y in range(480,546,5):
            skin=span(face,y)
            if not skin:continue
            edge=skin[int(right)];hits=np.flatnonzero(crown[y,edge+1:] if right else crown[y,:edge][::-1])
            if len(hits) and hits[0]>1:
                gap=int(hits[0]);x=edge+(gap+1)*(1 if right else -1)
                add([x,y],[(1-gap)*(1 if right else -1),0],8,True)
    # Keep the already connected stem neighbourhood at its prior location.
    # This constrains attachment points rather than freezing whole latitudes.
    rest=np.array([v['xy'] for v in vertices])
    for anchor in pose.get('anchors',[]):
        for dy in [-50,-32,-12]:
            for dx in [-12,0,12]:
                pixel=np.array([anchor[0]+dx,anchor[1]+dy])
                ids=np.argsort(((rest-pixel)**2).sum(axis=1))[:3]
                for i in ids:
                    if np.linalg.norm(rest[i]-pixel)<35:
                        for n in [(1.,0.),(0.,1.)]:rows.append((grid[i],np.zeros(2),30,np.array(n)))
    c,d,w,n=map(np.array,zip(*rows))
    return dict(name=name,yaw=pose['yaw'],pitch=pose['pitch'],c=c,d=d,w=w,normal=n)


def silhouette_weight(y,slope):
    y_weight=1.25 if y<=220 else (.55 if 260<=y<=360 else .85)
    # add() normalizes (1,-slope). Undo that normalization so this term
    # measures the horizontal row-span error used by the raster gate.
    return y_weight*(1+slope**2)


def conformal_rows():
    """Cell-center CR derivatives in (160*s, restY) pixels, area weighted.

    Uniform scale/rotation have zero energy. This is conformal, not full ARAP.
    """
    rows=[];dx=(S[1]-S[0])*160;dy=Y[1]-Y[0]
    for j in range(15):
        for i in range(11):
            ids=[j*12+i,j*12+i+1,(j+1)*12+i,(j+1)*12+i+1]
            ds=np.zeros(192);ds[ids]=np.array([-1,1,-1,1])/(2*dx)
            dt=np.zeros(192);dt[ids]=np.array([-1,-1,1,1])/(2*dy)
            rows.extend([np.r_[ds,-dt],np.r_[dt,ds]])
    return np.array(rows)*np.sqrt(dx*dy)


def mirror_operator():
    mirror=np.eye(192).reshape(16,12,192)[:,::-1].reshape(192,192)
    return np.kron(np.diag([-1.,1.]),mirror)


def solve_joint(systems,r,conformal=.5,symmetry=.2,view=.05,held_out=None):
    """Joint normal equations; held-out observations contribute no data.

    Weak adjacent-yaw coupling also predicts a missing neutral chart.
    """
    count=len(systems);size=384;mirror=mirror_operator();identity=np.eye(size)
    projections=[(identity+mirror)/2 if p['yaw']==0 else identity for p in systems]
    cr=conformal_rows();matrix=np.zeros((count*size,count*size));rhs=np.zeros(count*size)
    designs=[]
    for k,p in enumerate(systems):
        projection=projections[k];n=p['normal']
        c=np.c_[p['c']*n[:,0,None],p['c']*n[:,1,None]]@projection
        d=np.sum(p['d']*n,axis=1);designs.append((c,d))
        sl=slice(k*size,(k+1)*size);reg=cr@projection
        matrix[sl,sl]=np.kron(np.eye(2),r[k] if isinstance(r,list) else r)+conformal*(reg.T@reg)
        if p['name']!=held_out:
            matrix[sl,sl]+=c.T@(p['w'][:,None]*c)
            rhs[sl]=c.T@(p['w']*d)
    def couple(a,b,weight,transform):
        left=projections[a];right=transform@projections[b]
        sa=slice(a*size,(a+1)*size);sb=slice(b*size,(b+1)*size)
        matrix[sa,sa]+=weight*left.T@left;matrix[sb,sb]+=weight*right.T@right
        cross=weight*left.T@right
        matrix[sa,sb]-=cross;matrix[sb,sa]-=cross.T
    by_yaw={p['yaw']:k for k,p in enumerate(systems)}
    couple(by_yaw[-45],by_yaw[45],symmetry,mirror)
    for a,b in [(-45,0),(0,45)]:couple(by_yaw[a],by_yaw[b],view,identity)
    q=np.linalg.solve(matrix,rhs);poses=[]
    for k,p in enumerate(systems):
        v=projections[k]@q[k*size:(k+1)*size];du=v.reshape(2,192).T
        c,d=designs[k];error=d-c@v
        stats=dict(observations=len(d),duRms=float(np.sqrt(np.mean(np.sum(du**2,axis=1)))),
                   duMax=float(np.linalg.norm(du,axis=1).max()),
                   predictedRms=float(np.sqrt(np.average(error**2,weights=p['w']))),
                   priorRms=float(np.sqrt(np.average(d**2,weights=p['w']))))
        poses.append(dict(name=p['name'],yaw=p['yaw'],pitch=p['pitch'],du=du.tolist(),stats=stats))
    return poses


def solve_residual(p,r):
    n=p['normal'];cx=p['c'].copy();cy=cx.copy()
    if p['yaw']==0:
        mirror=cx.reshape(-1,16,12)[:,:,::-1].reshape(-1,192)
        cx=(cx-mirror)*.5;cy=(cy+mirror)*.5
    c=np.concatenate([cx*n[:,0,None],cy*n[:,1,None]],axis=1)
    w=p['w'];d=np.sum(p['d']*n,axis=1)
    q=np.linalg.solve(c.T@(w[:,None]*c)+np.kron(np.eye(2),r),c.T@(w*d))
    du=q.reshape(2,192).T.copy()
    if p['yaw']==0:
        grid=du.reshape(16,12,2)
        grid[:,:,0]=(grid[:,:,0]-grid[:,::-1,0])*.5
        grid[:,:,1]=(grid[:,:,1]+grid[:,::-1,1])*.5
    error=d-c@q
    stats=dict(observations=len(d),duRms=float(np.sqrt(np.mean(np.sum(du**2,axis=1)))),
               duMax=float(np.linalg.norm(du,axis=1).max()),
               predictedRms=float(np.sqrt(np.average(error**2,weights=w))),
               priorRms=float(np.sqrt(np.average(d**2,weights=w))))
    return dict(name=p['name'],yaw=p['yaw'],pitch=p['pitch'],du=du.tolist(),stats=stats)


def fit_joint(group,conformal=.5,symmetry=.2,view=.05,scale=1.,held_out=None):
    r=regularizer();scales=np.full(len(group),scale)
    for iteration in range(20):
        result=solve_joint(group,[r*v for v in scales],conformal,symmetry,view,held_out)
        exceeded=np.array([p['stats']['duRms']>45 or p['stats']['duMax']>115 for p in result])
        if not exceeded.any():break
        scales[exceeded]*=2
    else:raise ValueError('Residual budget infeasible')
    for pose,v in zip(result,scales):
        pose['regularization']=dict(ridge=.5*v,xSecondDifference=2*v,ySecondDifference=50*v,
                                    conformal=conformal,symmetry=symmetry,view=view,scale=v)
    return result


def fit_lower(poses,features,captures):
    """Fit bead-local affine row spans; positive scales preserve orientation."""
    from probe_hair_only import reference,read_mask,span
    tau=np.linspace(0,1,8);result=[]
    for pose in poses:
        name=pose['name'];ref=reference(features[name])
        current=read_mask(captures/(name+'-tails.png'))|read_mask(captures/(name+'-ties.png'))
        row=dict(name=name,yaw=pose['yaw'],pitch=pose['pitch'])
        for side,(lo,hi,root) in {'left':(0,502,[306.5,544.2]),'right':(502,1024,[691.5,542.6])}.items():
            # The tie image measures the unchanged rig's pose-specific anchor.
            tie=read_mask(captures/(name+'-ties.png'))[:,lo:hi]
            yy,xx=np.where(tie);anchor_x=(np.percentile(xx,2)+np.percentile(xx,98))/2+lo
            anchor_y=(np.percentile(yy,2)+np.percentile(yy,98))/2
            samples=[]
            for y in range(max(550,int(anchor_y+22)),721,4):
                a,b=span(current[:,lo:hi],y),span(ref['mask'][:,lo:hi],y)
                if a and b and a[1]-a[0]>8 and b[1]-b[0]>8:
                    a=np.array(a,float)+lo;b=np.array(b,float)+lo
                    scale=np.clip((b[1]-b[0])/(a[1]-a[0]),.3,3.)
                    shift=float(b.mean()-anchor_x-scale*(a.mean()-anchor_x))
                    # sag is present in the base rig; map its vertical length
                    # back to the authored tau using the unchanged pendulum.
                    dy=y-anchor_y;lift=max(0,root[1]-anchor_y)
                    for _ in range(8):dy=y-anchor_y-lift*.72*np.clip(dy/635,0,1)**.62
                    t=np.clip(dy/200,0,1);i=min(6,int(t*7));v=t*7-i
                    c=np.zeros(8);c[i]=1-v;c[i+1]=v
                    rest_y=root[1]+dy;f=np.clip((rest_y-544.2)/(565-544.2),0,1);f=f*f*(3-2*f)
                    if f>.2:samples.append((c*f,[shift,scale-1]))
            c=np.array([s[0] for s in samples]);d=np.array([s[1] for s in samples])
            smooth=np.diff(np.eye(8),2,axis=0)
            reg=.05*np.eye(8)+2*smooth.T@smooth;reg[0,0]+=1000
            # The first three nodes include the complete bead/tie footprint.
            # Eliminate them from the solve so the tie silhouette stays exact.
            q=np.zeros((8,2));q[3:]=np.linalg.solve((c.T@c+reg)[3:,3:],(c.T@d)[3:])
            q[:,1]=np.clip(q[:,1],-.7,2)
            row[side]=np.c_[q[:,0],1+q[:,1]].tolist()
        result.append(row)
    return dict(tau=tau.tolist(),poses=result,frame='bead-local horizontal affine spans; restY<=544.2 fixed; fade to565')


def chart_derivatives():
    # Match the independent JS chart gate, including its pole half-width.
    sections=json.loads(subprocess.check_output(['node','--input-type=module','-e',
        "import {domeSection} from './bundle/hair-surface.mjs'; console.log(JSON.stringify(Array.from({length:15},(_,j)=>domeSection(Math.max(60,(j+.5)*545/15)).rx)))"],cwd=ROOT))
    ds=[];dy=[]
    for j in range(15):
        for i in range(11):
            for a in [.001,.5,.999]:
                for b in [.001,.5,.999]:
                    s=S[i]+a*(S[i+1]-S[i]);y=Y[j]+b*(Y[j+1]-Y[j])
                    ds.append((stencil(s+1e-5,y)-stencil(s-1e-5,y))/(2e-5*sections[j]))
                    dy.append((stencil(s,y+1e-3)-stencil(s,y-1e-3))/(2e-3))
    return np.array(ds),np.array(dy)


def project_orientation(du,yaw,ds,dy,mobility=None):
    """Linearized determinant projection, local to the violating cells.

    This keeps the fitted exterior instead of damping the complete head just
    because a small hairline cell contracts. Final JS sampling is independent.
    """
    q=np.array(du).copy()
    for _ in range(30):
        ux,vx=(ds@q).T;uy,vy=(dy@q).T;det=(1+ux)*(1+vy)-uy*vx
        if det.min()>=.27:break
        bad=det<.28
        gx=(1+vy[bad,None])*ds[bad]-vx[bad,None]*dy[bad]
        gy=(1+ux[bad,None])*dy[bad]-uy[bad,None]*ds[bad]
        if yaw==0:
            gx=(gx-gx.reshape(-1,16,12)[:,:,::-1].reshape(-1,192))*.5
            gy=(gy+gy.reshape(-1,16,12)[:,:,::-1].reshape(-1,192))*.5
        g=np.c_[gx,gy]
        response=g.T if mobility is None else mobility@g.T
        change=(response@np.linalg.solve(g@response+1e-7*np.eye(len(g)),.3-det[bad])).reshape(2,192).T
        energy=np.square(np.maximum(0,.28-det)).sum();best=q
        for step in [1.,.5,.25,.125,.0625]:
            candidate=q+step*change;xx,yx=(ds@candidate).T;xy,yy=(dy@candidate).T
            score=np.square(np.maximum(0,.28-((1+xx)*(1+yy)-xy*yx))).sum()
            if score<energy:energy=score;best=candidate
        if best is q:break
        q=best
    magnitude=np.linalg.norm(q,axis=1);rms=np.sqrt(np.mean(magnitude**2))
    q*=min(1,(45-1e-9)/max(rms,1e-9),(115-1e-9)/max(magnitude.max(),1e-9))
    return q.tolist()


def limit_orientation(poses,systems=None):
    """Project bad cells first, then retain a final independent backstop."""
    ds,dy=chart_derivatives()
    for k,pose in enumerate(poses):
        mobility=None
        if systems is not None:
            system=systems[k];n=system['normal'];c=np.c_[system['c']*n[:,0,None],system['c']*n[:,1,None]]
            r=regularizer()*pose['regularization']['scale'];cr=conformal_rows()
            h=np.kron(np.eye(2),r)+pose['regularization']['conformal']*(cr.T@cr)+c.T@(system['w'][:,None]*c)+.05*np.eye(384)
            mobility=np.linalg.inv(h)
            if not pose['yaw']:
                projection=(np.eye(384)+mirror_operator())/2;mobility=projection@mobility@projection
        pose['du']=project_orientation(pose['du'],pose['yaw'],ds,dy,mobility)
    data=empty_data();data['poses']=poses
    for _ in range(30):
        write(data)
        metrics=json.loads(subprocess.check_output(['node',str(ROOT/'pipeline/hair_solve_metrics.mjs')],timeout=60))
        failed={p['name'] for p in metrics['poses'] if p['minDet']<.25 or p['reversedCells']}
        if not failed:break
        for pose in poses:
            if pose['name'] in failed:pose['du']=(np.array(pose['du'])*.95).tolist()
    else:raise ValueError('Orientation backtracking infeasible')
    for pose in poses:
        du=np.array(pose['du']);pose['stats'].update(duRms=float(np.sqrt(np.mean(np.sum(du**2,axis=1)))),duMax=float(np.linalg.norm(du,axis=1).max()))
    return poses


def limit_lower_orientation(data):
    for _ in range(20):
        write(data)
        metrics=json.loads(subprocess.check_output(['node',str(ROOT/'pipeline/hair_solve_metrics.mjs')],timeout=60))
        failed=[p for p in metrics['lower']['poses'] if p['minDet']<.25 or p['reversedTriangles']]
        if not failed:return
        for pose in data['lower']['poses']:
            if any(p['pitch']*pose['pitch']>0 and abs(p['yaw']-pose['yaw'])<=45 for p in failed):
                for side in ['left','right']:
                    q=np.array(pose[side]);q[:,0]*=.9;q[:,1]=1+(q[:,1]-1)*.9;pose[side]=q.tolist()
    raise ValueError('Lower orientation backtracking infeasible')


def evaluate(base):
    """Paired normal observations using each model's own spatial basis."""
    import types
    from hair_solve_quality import compare_captures
    old=types.ModuleType('baseline_fit');old.__file__=__file__
    exec(subprocess.check_output(['git','show',base+':pipeline/fit_hair_solve.py'],cwd=ROOT),old.__dict__)
    inputs=json.loads(subprocess.check_output(['node',str(ROOT/'pipeline/hair_solve_inputs.mjs')]))
    features={p['name']:p for p in json.loads((ROOT/'source/viewer/face-feature-fit.json').read_text())['poses']}
    before=json.loads(subprocess.check_output(['git','show',base+':source/viewer/hair-solve.json'],cwd=ROOT))
    after=json.loads((ROOT/'source/viewer/hair-solve.json').read_text())
    systems=[observations(p,features[p['name']],ROOT/'debug/hair_solve_prior') for p in inputs]
    domains={p['name']:observations(p,features[p['name']],ROOT/'debug/hair_solve_prior',basis=old.stencil) for p in inputs}
    def rms(system,du):
        error=np.sum((system['c']@np.array(du)-system['d'])*system['normal'],axis=1)
        return float(np.sqrt(np.average(error**2,weights=system['w'])))
    rows=[]
    for held in systems:
        name=held['name'];group=[s for s in systems if s['pitch']==held['pitch']]
        settings=next(p for p in after['poses'] if p['name']==name)['regularization']
        fitted=fit_joint(group,settings['conformal'],settings['symmetry'],settings['view'],settings['scale'],held_out=name)
        prediction=next(p for p in fitted if p['name']==name)
        rows.append(dict(heldOut=name,sampleCount=len(held['d']),
                         before=dict(pinRms=rms(domains[name],next(p for p in before['poses'] if p['name']==name)['du']),lopoRms=rms(domains[name],np.zeros((192,2)))),
                         after=dict(pinRms=rms(held,next(p for p in after['poses'] if p['name']==name)['du']),lopoRms=rms(held,prediction['du']))))
    means={variant:{key:float(np.mean([p[variant][key] for p in rows])) for key in ['pinRms','lopoRms']} for variant in ['before','after']}
    raster=dict(main=compare_captures(list(features.values()),ROOT/'debug/hair_solve_prior',ROOT/'debug/vdd_main'),
                after=compare_captures(list(features.values()),ROOT/'debug/hair_solve_prior',ROOT/'debug/hair_h0/current'))
    return dict(rasterCaptures=raster,hair=dict(definition='identical raster observations with each model own basis (old y584 / split y545)',folds=rows,mean=means,heldOutPolicy='held-out pose data excluded from joint fit'))


