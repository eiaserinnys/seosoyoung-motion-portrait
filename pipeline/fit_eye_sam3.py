"""Export the approved v2.9.1 fit, including the corrected neutral delta0.

Run measure_eye_masks.py, eye_fit_quality.py, then this exporter. The evaluator
owns fitting; this step only serializes the same tables and coefficients.
"""
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]

def export_fit(measurement, evaluation, bootstrap):
    result = dict(schema='2.9.1', mirror=False, rho=bootstrap['rho'],
                  lambdaH=bootstrap['lambdaH'], achieved=bootstrap['achieved'],
                  gaze={}, status=evaluation['status'], warnings=evaluation['warnings'],
                  noise=evaluation['noise'],
                  dependencies='Cleanup seeds, centroid inversion and bObserved use K; sigma includes pose variation within 4 degrees.',
                  nasalCutDepth='Observed mask nasal overrun; not reconstructed hidden iris width.',
                  aLaw='cos(max(theta,0))')
    for side in ['left', 'right']:
        r = measurement['rest'][side]
        rest = dict(r)
        for key in ['cO', 'cI']:
            rest[key] = (np.array(r[key])+[152.,20.]).tolist()
        rest['cH'] = bootstrap['front'][side]['cH']
        rest['anchor'] = bootstrap['front'][side]['anchor']
        phi = r['phi']
        rest['E'] = [[float(np.cos(phi)), float(-np.sin(phi))],
                     [float(np.sin(phi)), float(np.cos(phi))]]
        f = evaluation['fit'][side]
        result[side] = dict(K=measurement['K'][side], w0=measurement['K'][side]['w'],
                            delta0=r['delta'], rest=rest,
                            knotsDeg=f['dTemp']['knotsDeg'], r_T=f['dTemp']['knotLogs'],
                            r_N=f['dNas']['knotLogs'], h=f['h']['coefficients'][:4],
                            deltaNu=f['deltaY']['coefficients'][:4],
                            kappa=1)
        # Retain measured v2.2 main-axis gaze distances with the specified K.w.
        negative, positive, vertical = bootstrap['gaze'][side]['legacyMainAxisPx']
        radius = result['rho']*result[side]['w0']
        gn, gt = np.arcsin(np.array([min(-negative, positive),max(-negative, positive)])/radius)
        result['gaze'][side] = dict(a=float((gt+gn)/2), b=float((gt-gn)/2),
                                    Gy=float(-np.arcsin(vertical/radius)),
                                    legacyMainAxisPx=[negative,positive,vertical])
    return result

def main():
    read=lambda path:json.loads((ROOT/path).read_text())
    result=export_fit(read('source/viewer/sam3-eye-measurements.json'),
                      read('debug/sam3-eye-v291/evaluation.json'),
                      read('source/references/seedance/eye-bootstrap.json'))
    (ROOT/'source/viewer/sam3-eye-fit.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    (ROOT/'bundle/eye-sam3-data.mjs').write_text('// Generated by pipeline/fit_eye_sam3.py.\nexport const EYE_SAM3='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n')
    print('EXPORTED v2.9.1 mirror=false delta0=rest.delta w0=K.w; beta excluded')

if __name__ == '__main__':
    main()
