#!/usr/bin/env python3
"""Build the standalone viewer from the authored template and correction schema."""
import json
import shutil
from pathlib import Path
from stage3_build_atlas_and_rig import build
ROOT=Path(__file__).resolve().parents[1]
def build_viewer():
    from fit_features import build as fit_features
    fit_features()
    from fit_outline import build as fit_outline
    fit_outline()
    from fit_dome import build as fit_dome
    fit_dome()
    build()
    from canopy_mesh import update as update_canopy
    update_canopy()
    config=json.loads((ROOT/'source/viewer/corrections.json').read_text())
    module='// Generated by pipeline/stage3_build_viewer.py.\n'
    module+='export const CORRECTION_CONTROLS='+json.dumps(config['controls'],ensure_ascii=False)+';\n'
    module+='export const CORRECTION_PRESETS='+json.dumps(config['presets'],ensure_ascii=False)+';\n'
    (ROOT/'bundle/corrections.mjs').write_text(module)
    shutil.copyfile(ROOT/'source/viewer/index.html',ROOT/'bundle/index.html')
    shutil.copyfile(ROOT/'src/head-turn.mjs',ROOT/'bundle/head-turn.mjs')
    rig_file=ROOT/'bundle/assets/seosoyoung-rig.json'
    rig=json.loads(rig_file.read_text());rig['corrections']=config
    rig_file.write_text(json.dumps(rig,ensure_ascii=False,separators=(',',':')))
    dist=ROOT/'dist'
    if dist.exists():shutil.rmtree(dist)
    shutil.copytree(ROOT/'bundle',dist)
    print('PASS viewer template, correction schema and shared deformation module')
if __name__=='__main__':build_viewer()
